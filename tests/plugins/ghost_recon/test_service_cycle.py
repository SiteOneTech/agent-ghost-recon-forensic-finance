def test_open_case_between_seal_and_rerun_keeps_audited_hashes(store, demo_case):
    """The skills call gr_case_open before gr_audit_start(rerun): that must not turn new files into DUP_PRIOR
    nor hide a tampered audited file (regression for the review finding)."""
    cid, a = _initial(store, demo_case)
    aid = a["audit"]["id"]
    service.seal_audit(store, aid, force=True)
    (demo_case / "Bancos" / "nuevo.txt").write_text("nuevo", encoding="utf-8")
    (demo_case / "Facturas" / "FAC-2026-002.csv").write_text("tampered", encoding="utf-8")
    service.open_case(store, str(demo_case))          # the step the orchestrator skills perform first
    b = service.start_audit(store, cid, "rerun")
    ev = b["evidence"]
    assert ev["NEW"] == 1 and ev.get("MODIFIED") == 1 and ev.get("DUP_PRIOR", 0) == 0
    assert b["audit"]["summary"]["modified_evidence"] == ["Facturas/FAC-2026-002.csv"]
    plan = swarm.plan_extraction(store, b["audit"]["id"])
    assert sorted(f["rel"] for t in plan["tasks"] for f in json.loads(Path(t["manifest"]).read_text(encoding="utf-8"))["files"]) == \
        ["Bancos/nuevo.txt", "Facturas/FAC-2026-002.csv"]
    row = next(e for e in store.list_evidence(cid) if e["path"] == "Facturas/FAC-2026-002.csv")
    assert row["meta"]["previous_hashes"][0]["audit_id"] == aid


def test_unreadable_zip_member_does_not_abort_intake(store, demo_case):
    import zipfile
    # a member flagged as encrypted: zipfile raises RuntimeError on open (no password)
    z = demo_case / "Bancos" / "cifrado.zip"
    with zipfile.ZipFile(z, "w") as zf:
        zf.writestr("secreto.csv", "a,b")
    data = bytearray(z.read_bytes())
    # set the encryption bit (bit 0 of general purpose flags) in the local header and central directory
    for sig in (b"PK\x03\x04", b"PK\x01\x02"):
        i = data.find(sig)
        off = 6 if sig == b"PK\x03\x04" else 8
        data[i + off] |= 1
    z.write_bytes(bytes(data))
    s = service.open_case(store, str(demo_case))
    rows = {e["path"]: e for e in store.list_evidence(s["case"]["id"])}
    assert rows["Bancos/cifrado.zip::secreto.csv"]["status"] == "UNREADABLE"
    a = service.start_audit(store, s["case"]["id"], "initial")
    assert a["evidence"].get("UNREADABLE") == 1
